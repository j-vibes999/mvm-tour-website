#!/usr/bin/env python3
"""Regenerate small, uncropped WebP derivatives from the existing local photos.

Run with: python3 scripts/generate-thumbnails.py
Requires Pillow with WebP support and the project's Node.js runtime. Main photo
files are read only; outputs are thumbnails/ and media-thumbnails.js.
"""

import json
from pathlib import Path
import subprocess

from PIL import Image, ImageOps


PROJECT = Path(__file__).resolve().parent.parent
DIST = PROJECT / "dist"
WIDTHS = (160, 320)


def main():
    result = subprocess.run(
        ["node", "--input-type=module", "-e",
         "import {localPhotos} from './dist/complete-media.js'; console.log(JSON.stringify(localPhotos));"],
        cwd=PROJECT, check=True, capture_output=True, text=True,
    )
    photos = json.loads(result.stdout)
    output = DIST / "assets/images/thumbnails"
    output.mkdir(parents=True, exist_ok=True)
    catalog = {}
    total_bytes = 0

    for key, photo in sorted(photos.items()):
        source_path = photo["srcset"].split(",")[-1].strip().split(" ")[0]
        with Image.open(DIST / source_path) as source:
            image = ImageOps.exif_transpose(source).convert("RGB")
            catalog[key] = []
            for width in WIDTHS:
                if width > image.width:
                    continue
                height = round(image.height * width / image.width)
                resized = image.resize((width, height), Image.Resampling.LANCZOS)
                target = output / f"{key}-{width}.webp"
                options = {"quality": 82, "method": 6}
                if source.info.get("icc_profile"):
                    options["icc_profile"] = source.info["icc_profile"]
                resized.save(target, "WEBP", **options)
                total_bytes += target.stat().st_size
                catalog[key].append(width)

    source = (
        "// Generated by scripts/generate-thumbnails.py; uncropped local photo derivatives.\n"
        "export const photoThumbnails = " + json.dumps(catalog, ensure_ascii=False, indent=2) + ";\n"
    )
    (DIST / "media-thumbnails.js").write_text(source)
    print(f"Generated {sum(map(len, catalog.values()))} thumbnails for {len(catalog)} photos: {total_bytes:,} bytes")


if __name__ == "__main__":
    main()
