// Run after editing map-data.js: node scripts/generate-map-sprite.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import { laosMap } from '../dist/map-data.js';

const dist = new URL('../dist/', import.meta.url);
const maps = new URL('assets/maps/', dist);
await mkdir(maps, { recursive: true });

// Same original coordinate space as the inline shapes. Each caller retains its
// own square viewport, so referencing a path does not change its scale or crop.
const shapes = Object.entries(laosMap.provinces);
const attribution = 'Source: geoBoundaries LAO ADM1 (OpenStreetMap contributors, ODbL 1.0).';
const paths = shapes.map(([id, shape]) => `<path id="province-${id}" d="${shape.d}" vector-effect="non-scaling-stroke"/>`).join('\n');
await writeFile(new URL('provinces.svg', maps), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${laosMap.viewBox}">\n<!-- ${attribution} -->\n<defs>\n${paths}\n</defs>\n</svg>\n`);
await writeFile(new URL('province-bounds.js', dist), `// Generated by scripts/generate-map-sprite.mjs. ${attribution}\nexport const provinceBounds = ${JSON.stringify(Object.fromEntries(shapes.map(([id, shape]) => [id, shape.b])))};\n`);
console.log(`Generated one SVG sprite and compact bounds for ${shapes.length} provinces.`);
