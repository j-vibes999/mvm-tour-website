// Reviewed paired dictionaries remain the source of truth. Run after editing them:
// node scripts/generate-locales.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';
import reviewed from '../dist/locales/all.js';

const output = process.argv[2] ? resolve(process.argv[2]) : fileURLToPath(new URL('../dist/locales/', import.meta.url));
await mkdir(output, { recursive: true });
for (const [lang, index] of [['lo', 0], ['zh', 1]]) {
  const catalogue = Object.fromEntries(Object.entries(reviewed).map(([key, pair]) => {
    if (typeof pair[index] !== 'string') throw new Error(`Missing reviewed ${lang} translation: ${key}`);
    return [key, pair[index]];
  }));
  await writeFile(join(output, `${lang}.js`), `// Generated by scripts/generate-locales.mjs from the reviewed paired dictionaries.\nexport default ${JSON.stringify(catalogue, null, 2)};\n`);
}
console.log('Generated 2 language catalogues (lo, zh).');
